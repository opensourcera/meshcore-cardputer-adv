"""Generate a VLW font as a C header from a TTF, matching the Unicode blocks of the original DejaVu Sans 12 font.
usage: python make_vlw_font.py <ttf> <pixel size> <out.h> <array name>"""
import struct, sys
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ttf, px, out_path, name = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
BLOCKS = [(0x20, 0x7E), (0xA0, 0xFF), (0x100, 0x17F), (0x400, 0x4FF), (0x20A0, 0x20CF), (0x2190, 0x21FF)]
cmap = TTFont(ttf).getBestCmap()
font = ImageFont.truetype(ttf, px)
ascent, descent = font.getmetrics()
EMPTY = bytes(1)

glyphs = []
for lo, hi in BLOCKS:
    for cp in range(lo, hi + 1):
        if cp not in cmap:
            continue
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        pad = px
        canvas = Image.new('L', (adv + 2 * pad, ascent + descent + 2 * pad), 0)
        ImageDraw.Draw(canvas).text((pad, pad), ch, font=font, fill=255)
        box = canvas.getbbox()
        if box is None:
            glyphs.append((cp, 1, 1, adv, 0, 0, EMPTY))
            continue
        x0, y0, x1, y1 = box
        glyphs.append((cp, y1 - y0, x1 - x0, adv, (pad + ascent) - y0, x0 - pad, canvas.crop(box).tobytes()))

hdr = struct.pack('>6i', len(glyphs), 11, px, 0, ascent, descent)
table = b''.join(struct.pack('>7i', cp, h, w, adv, top, left, 0) for cp, h, w, adv, top, left, _ in glyphs)
bitmaps = b''.join(g[6] for g in glyphs)
data = hdr + table + bitmaps

with open(out_path, 'w') as f:
    f.write('#pragma once\n\n// DejaVu Sans %d px, VLW format, generated by tools/make_vlw_font.py\n' % px)
    f.write('// Unicode blocks: Basic Latin, Latin-1 Supplement, Latin Extended-A, Cyrillic, Currency Symbols, Arrows\n\n')
    f.write('static const uint8_t %s[] PROGMEM = {\n' % name)
    for i in range(0, len(data), 16):
        f.write('  ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n')
print('%s: %d glyphs, ascent %d descent %d, %d bytes' % (name, len(glyphs), ascent, descent, len(data)))
